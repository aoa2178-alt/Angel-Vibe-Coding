// api/_knowledge.js is the reference text the "Ask Claude" server function sends with each question: llms.txt plus the
// FAQ. It is generated from those two sources. Run `UPDATE_KNOWLEDGE=1 npx vitest run knowledge` after changing either.
import { readFileSync, writeFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { FAQ_GROUPS } from "./faq";

const FILE = new URL("../../api/_knowledge.js", import.meta.url);

function knowledge() {
  const llms = readFileSync(new URL("../../public/llms.txt", import.meta.url), "utf8").replace(/\r\n/g, "\n").trim();
  const faq = FAQ_GROUPS.map((g) => `### ${g.title}\n\n${g.items.map((i) => `Q: ${i.q}\nA: ${i.a}`).join("\n\n")}`).join("\n\n");
  const text = `${llms}\n\n## FAQ\n\n${faq}`;
  return `// Generated by src/lib/knowledge.test.ts from public/llms.txt and src/lib/faq.ts. Do not edit by hand.\nexport const KNOWLEDGE = ${JSON.stringify(text)};\n`;
}

describe("Ask Claude reference text", () => {
  it("is up to date with llms.txt and the FAQ", () => {
    const want = knowledge();
    if (process.env.UPDATE_KNOWLEDGE) writeFileSync(FILE, want);
    expect(readFileSync(FILE, "utf8").replace(/\r\n/g, "\n")).toBe(want);
  });
});
